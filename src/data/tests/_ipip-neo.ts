/** تبدیل ردیف خام هنجار به {کلید مقیاس: میانگین و انحراف معیار} */
function toGroup(n: RawNorm): BuiltInNormGroup {
  const values: BuiltInNormGroup["values"] = {};
  DOMAIN_ORDER.forEach((d, di) => {
    values[d] = { mean: n.ns[di], sd: n.ns[5 + di] };
    for (let k = 0; k < 6; k++) values[facetKey(d, k + 1)] = { mean: n.ns[10 + di * 12 + k], sd: n.ns[10 + di * 12 + 6 + k] };
  });
  return { sex: n.sex, ageMin: n.ageMin, ageMax: n.ageMax, label: n.label, values };
}

