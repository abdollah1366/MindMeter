/**
 * سازنده‌ی سؤال‌های آزمون هوش مایندمتر.
 * - ماتریس‌ها و دنباله‌های عددی از روی «قاعده» ساخته می‌شوند، پس پاسخ درست همیشه از خود قاعده می‌آید.
 * - گزینه‌های غلط با تغییر یکی از ویژگی‌های پاسخ درست ساخته می‌شوند تا فقط یک گزینه با قاعده سازگار باشد.
 * - چینش گزینه‌ها با یک مولد تصادفی ثابت (seed) انجام می‌شود تا در سرور و مرورگر یکسان باشد.
 */
import type { AnswerOption, Glyph, PsychTest, Question } from "@/lib/types";
import { toPersianDigits } from "@/lib/scoring";

export type Level = NonNullable<Question["level"]>;
type Shape = Glyph["shape"];
type Fill = NonNullable<Glyph["fill"]>;

/** مولد تصادفی قطعی */
export function rng(seed: number) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function hash(s: string) {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 16777619);
  return h >>> 0;
}

function shuffle<T>(arr: T[], rand: () => number) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

export const g = (shape: Shape, count = 1, fill: Fill = "solid", rotate = 0): Glyph => ({ shape, count, fill, rotate });

const same = (a: Glyph, b: Glyph) =>
  a.shape === b.shape && (a.count ?? 1) === (b.count ?? 1) && (a.fill ?? "solid") === (b.fill ?? "solid") && ((a.rotate ?? 0) % 360) === ((b.rotate ?? 0) % 360);

const MATRIX_TEXT = "کدام گزینه جای علامت سؤال را پر می‌کند؟ الگوی ردیف‌ها و ستون‌ها را پیدا کنید.";

/** سؤال ماتریس با گزینه‌های دستی (برای فرم کوتاه) */
export function matrixItem(id: string, level: Level, cells: (Glyph | null)[], options: Glyph[], answer: number): Question {
  return {
    id,
    level,
    scale: "matrix",
    text: MATRIX_TEXT,
    figure: { kind: "matrix", cells },
    options: options.map((figure, i): AnswerOption => ({ label: toPersianDigits(i + 1), value: i, figure })),
    answer,
  };
}

/** سؤال ماتریس از روی تابع خانه‌ها؛ گزینه‌های غلط از تغییر ویژگی‌های پاسخ ساخته می‌شوند */
function matrixFromRule(id: string, level: Level, cell: (r: number, c: number) => Glyph, shapes: Shape[], optionCount: number): Question {
  const rand = rng(hash(id));
  const cells = Array.from({ length: 9 }, (_, i) => (i === 8 ? null : cell(Math.floor(i / 3), i % 3)));
  const answer = cell(2, 2);
  const pool: Glyph[] = [];
  const n = answer.count ?? 1;
  if (answer.shape !== "arrow") for (const d of [1, -1, 2]) if (n + d >= 1 && n + d <= 4) pool.push({ ...answer, count: n + d });
  if (answer.shape !== "arrow") for (const s of shapes) if (s !== answer.shape) pool.push({ ...answer, shape: s });
  for (const f of (answer.shape === "arrow" ? ["solid", "empty"] : ["solid", "empty", "striped"]) as Fill[])
    if (f !== (answer.fill ?? "solid")) pool.push({ ...answer, fill: f });
  if (answer.shape === "arrow") for (const d of [45, 90, 135, 180, 225, 270, 315]) pool.push({ ...answer, rotate: ((answer.rotate ?? 0) + d) % 360 });
  // گزینه‌های غلطی که در ماتریس دیده می‌شوند جذاب‌ترند
  for (const c of cells) if (c && !same(c, answer)) pool.push(c);

  const distractors: Glyph[] = [];
  for (const d of shuffle(pool, rand)) {
    if (distractors.length >= optionCount - 1) break;
    if (same(d, answer) || distractors.some((x) => same(x, d))) continue;
    distractors.push(d);
  }
  const options = shuffle([answer, ...distractors], rand);
  return matrixItem(id, level, cells, options, options.findIndex((o) => same(o, answer)));
}

const SHAPE_SETS: [Shape, Shape, Shape][] = [
  ["circle", "square", "triangle"],
  ["diamond", "star", "circle"],
  ["square", "triangle", "diamond"],
  ["star", "circle", "square"],
  ["triangle", "diamond", "star"],
];
const FILLS: [Fill, Fill, Fill] = ["solid", "empty", "striped"];
const ALL_SHAPES: Shape[] = ["circle", "square", "triangle", "diamond", "star"];

/** ۳۶ ماتریس: ۱۲ ساده، ۱۲ متوسط، ۱۲ دشوار */
export function buildMatrices(prefix: string): Question[] {
  const out: Question[] = [];
  const add = (level: Level, cell: (r: number, c: number) => Glyph, opts = 4) =>
    out.push(matrixFromRule(`${prefix}${out.length + 1}`, level, cell, ALL_SHAPES, opts));

  // ── ساده: یک قاعده ──
  for (let k = 0; k < 4; k++) {
    const sh = SHAPE_SETS[k];
    const f = FILLS[k % 3];
    add("easy", (r, c) => g(sh[r], c + 1, f)); // شکل ثابت در ردیف، تعداد افزایشی
  }
  for (let k = 0; k < 4; k++) {
    const sh = SHAPE_SETS[(k + 1) % 5];
    const n = (k % 2) + 1;
    add("easy", (r, c) => g(sh[c], n, FILLS[(r + k) % 3])); // شکل در ستون، پُری در ردیف
  }
  for (let k = 0; k < 4; k++) {
    const sh = SHAPE_SETS[(k + 2) % 5];
    add("easy", (r, c) => g(sh[r], 3 - c, FILLS[(c + k) % 3] === "striped" ? "empty" : FILLS[(c + k) % 3])); // تعداد کاهشی
  }

  // ── متوسط: دو قاعده ──
  for (let k = 0; k < 3; k++) {
    const sh = SHAPE_SETS[k + 1];
    add("medium", (r, c) => g(sh[(r + c) % 3], ((r + c + k) % 3) + 1, FILLS[k])); // مربع لاتین شکل + تعداد
  }
  for (let k = 0; k < 3; k++) {
    const start = k * 90;
    add("medium", (r, c) => g("arrow", 1, k === 1 ? "empty" : "solid", (start + (r + c) * 90) % 360)); // چرخش ۹۰ درجه
  }
  for (let k = 0; k < 3; k++) {
    const sh: Shape[] = ["circle", "square", "diamond", "star"];
    const firsts = [
      [1, 2, 1 + (k % 2)],
      [2, 1, 1],
    ];
    add("medium", (r, c) => {
      const a = firsts[0][r];
      const b = firsts[1][r];
      return g(sh[(r + k) % 4], c === 0 ? a : c === 1 ? b : a + b, "solid"); // جمع: ستون سوم = اول + دوم
    });
  }
  for (let k = 0; k < 3; k++) {
    const sh = SHAPE_SETS[(k + 3) % 5];
    add("medium", (r, c) => g(sh[(r + 2 * c) % 3], 2, FILLS[(c + k) % 3])); // شکل لاتین + پُری ستونی
  }

  // ── دشوار: سه قاعده یا قاعده‌ی پنهان ──
  for (let k = 0; k < 4; k++) {
    const sh = SHAPE_SETS[k];
    add(
      "hard",
      (r, c) => g(sh[(r + c) % 3], ((2 * r + c + k) % 3) + 1, FILLS[(r + 2 * c + k) % 3]), // سه مربع لاتین با جایگشت‌های متفاوت
      5,
    );
  }
  for (let k = 0; k < 4; k++) {
    const steps = [45, 90, 135];
    const start = [0, 45, 90, 180][k];
    // پیکان‌ها فقط توپر یا توخالی‌اند تا هاشور در زاویه‌های مورب گیج‌کننده نشود
    add("hard", (r, c) => g("arrow", 1, (r + k) % 2 ? "empty" : "solid", (start + c * steps[r]) % 360), 5); // گام چرخش در هر ردیف متفاوت
  }
  for (let k = 0; k < 4; k++) {
    const sh = SHAPE_SETS[(k + 2) % 5];
    const tops = [
      [4, 3, 4],
      [3, 4, 4],
      [4, 4, 3],
      [3, 3, 4],
    ][k];
    const subs = [
      [1, 2, 3],
      [2, 1, 2],
      [3, 1, 1],
      [1, 2, 1],
    ][k];
    add("hard", (r, c) => g(sh[(r + c + k) % 3], c === 0 ? tops[r] : c === 1 ? subs[r] : tops[r] - subs[r], FILLS[(r + k) % 3]), 5); // تفریق + شکل لاتین
  }
  return out;
}

/** سؤال چندگزینه‌ای متنی */
export function choice(id: string, scale: string, level: Level, text: string, labels: string[], answer: number): Question {
  return { id, scale, level, text, options: labels.map((label, i) => ({ label, value: i })), answer };
}

const seriesText = (nums: number[]) => `این دنباله را کامل کنید:  ${nums.map(toPersianDigits).join("،  ")}،  ؟`;

/** سؤال دنباله‌ی عددی؛ گزینه‌های غلط نزدیک به پاسخ ساخته می‌شوند */
export function seriesItem(id: string, level: Level, terms: number[], answer: number, extraWrong: number[] = []): Question {
  const rand = rng(hash(id));
  const last = terms[terms.length - 1];
  const diff = Math.abs(answer - last) || 1;
  const pool = shuffle([...new Set([...extraWrong, answer + 1, answer - 1, answer + 2, answer - 2, answer + diff, answer - diff, last + diff * 2, answer + 10])], rand);
  const wrong = pool.filter((x) => x !== answer && x >= 0 && !terms.includes(x)).slice(0, 3);
  const values = shuffle([answer, ...wrong], rand);
  return choice(id, "numeric", level, seriesText(terms), values.map(toPersianDigits), values.indexOf(answer));
}

