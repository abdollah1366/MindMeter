/** بازه‌های موقت بر اساس درصد نمره از بیشینه */
function bands(max: number, title: string, high: string, low: string): ResultRange[] {
  const a = Math.floor(max * 0.24);
  const b = Math.floor(max * 0.44);
  const c = Math.floor(max * 0.64);
  return [
    { min: 0, max: a, title: "پایین", description: low, level: "normal" },
    {
      min: a + 1,
      max: b,
      title: "خفیف",
      description: `نشانه‌های خفیفی از «${title}» گزارش شده است؛ معمولاً جای نگرانی جدی نیست، ولی اگر ادامه دارد آن را زیر نظر داشته باشید.`,
      level: "mild",
    },
    {
      min: b + 1,
      max: c,
      title: "متوسط",
      description: `نشانه‌های «${title}» در حد متوسط است؛ بهتر است با یک روانشناس یا روانپزشک در میان بگذارید.`,
      level: "moderate",
    },
    { min: c + 1, max, title: "بالا", description: high, level: "high" },
  ];
}

const questions: Question[] = [];
const subScales: Scale[] = [];
for (const s of SUBS) {
  s.items.forEach((text, i) => {
    questions.push({
      id: `${s.key.toLowerCase()}${i + 1}`,
      text,
      scale: s.key,
      ...(s.crisis ? { alert: { minValue: 2, message: CRISIS_MESSAGE } } : {}),
      ...(s.critical?.includes(i) ? { critical: true } : {}),
    });
  });
  const max = s.items.length * 4;
  subScales.push({
    key: s.key,
    code: s.key,
    title: s.title,
    description: s.description,
    group: s.group,
    results: s.crisis
      ? [
          { min: 0, max: 0, title: "گزارش نشده", description: s.low, level: "normal" },
          { min: 1, max: 4, title: "نیازمند توجه", description: s.high, level: "high" },
          { min: 5, max, title: "نیازمند توجه فوری", description: s.high, level: "severe" },
        ]
      : bands(max, s.title, s.high, s.low),
  });
}

