const g = (shape: Glyph["shape"], count = 1, fill: Glyph["fill"] = "solid", rotate = 0): Glyph => ({ shape, count, fill, rotate });

const MATRIX_TEXT = "کدام گزینه جای علامت سؤال را پر می‌کند؟ الگوی ردیف‌ها و ستون‌ها را پیدا کنید.";

function matrix(id: string, cells: (Glyph | null)[], options: Glyph[], answer: number): Question {
  return {
    id,
    scale: "matrix",
    text: MATRIX_TEXT,
    figure: { kind: "matrix", cells },
    options: options.map((figure, i): AnswerOption => ({ label: toPersianDigits(i + 1), value: i, figure })),
    answer,
  };
}

function choice(id: string, scale: string, text: string, labels: string[], answer: number): Question {
  return { id, scale, text, options: labels.map((label, i) => ({ label, value: i })), answer };
}

